#!/usr/bin/env node
/** BUG-018 schema drift: offline SQL markers + optional live column check */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getSql } from './_lib/getSql.mjs';
import { describeDatabaseUrl } from '../api/_lib/dbConnection.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function loadEnvFile(filePath) {
  if (!filePath || !existsSync(filePath)) return;
  for (const line of readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!process.env[key] && value) process.env[key] = value;
  }
}

for (const name of ['.env', '.env.local']) loadEnvFile(join(root, name));
if (process.env.LIBERTE_ENV_FILE) loadEnvFile(resolve(process.env.LIBERTE_ENV_FILE));

const EXPECTED = {
  customers: ['id', 'phone', 'referred_by'],
  loyalty_events: ['id', 'customer_id', 'event_type'],
  in_app_notifications: ['id', 'target_type', 'is_active'],
  daily_claims: ['customer_id', 'type', 'day']
};

const MIGRATION_MARKERS = [
  { file: 'scripts/sql/013_loyalty_events_identity.sql', re: /GENERATED BY DEFAULT AS IDENTITY/ },
  { file: 'scripts/sql/014_schema_drift_columns.sql', re: /referred_by/ },
  { file: 'scripts/sql/014_schema_drift_columns.sql', re: /target_type/ },
  { file: 'scripts/sql/014_schema_drift_columns.sql', re: /uq_daily_claims_customer_type_day/ },
  { file: 'scripts/sql/002_realtime_setup.sql', re: /is_active/ },
  { file: 'scripts/sql/008_daily_claims_ensure.sql', re: /ADD COLUMN IF NOT EXISTS type/ }
];

const offline = { ok: true, checks: [] };
for (const item of MIGRATION_MARKERS) {
  const full = join(root, item.file);
  const exists = existsSync(full);
  const body = exists ? readFileSync(full, 'utf8') : '';
  const hit = exists && item.re.test(body);
  offline.checks.push({ file: item.file, ok: hit });
  if (!hit) offline.ok = false;
}

console.log(JSON.stringify({ step: 'offline', ...offline }, null, 2));
if (!offline.ok) process.exit(1);

const sql = getSql();
if (!sql) {
  console.log(JSON.stringify({ step: 'live', skipped: true, reason: 'DATABASE_URL_MISSING' }));
  process.exit(0);
}

const info = describeDatabaseUrl(process.env.DATABASE_URL || '');
const missing = [];
for (const [table, columns] of Object.entries(EXPECTED)) {
  const rows = await sql`
    SELECT column_name
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = ${table}
  `;
  const have = new Set(rows.map((r) => r.column_name));
  for (const col of columns) {
    if (!have.has(col)) missing.push({ table, column: col });
  }
}

const eventsId = await sql`
  SELECT pg_get_serial_sequence('public.loyalty_events', 'id') AS seq,
         (SELECT is_identity FROM information_schema.columns
          WHERE table_schema = 'public' AND table_name = 'loyalty_events' AND column_name = 'id') AS is_identity
`;

await sql.end({ timeout: 1 });

const report = {
  step: 'live',
  ok: missing.length === 0,
  provider: info.provider,
  hostMasked: info.hostMasked,
  missing,
  loyaltyEventsId: eventsId[0] || null
};
console.log(JSON.stringify(report, null, 2));
process.exit(report.ok ? 0 : 2);
